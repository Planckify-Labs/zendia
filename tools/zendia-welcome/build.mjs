// Builds the onboarding's interface into the one module the browser ships,
// src/zen/vendor/zendia-welcome.min.mjs (checked in, like motion.min.mjs).
//
//   node build.mjs            build it
//   node build.mjs --serve    build on every change and serve dev/ on
//                             http://127.0.0.1:4173, where the onboarding runs
//                             in an ordinary browser against a stand-in host

import { createReadStream, existsSync, statSync } from "node:fs";
import { createServer } from "node:http";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../..");
const outfile = path.join(repo, "src/zen/vendor/zendia-welcome.min.mjs");
const serve = process.argv.includes("--serve");

const banner = `// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at http://mozilla.org/MPL/2.0/.
//
// Generated by tools/zendia-welcome (npm run build:welcome); do not edit.
// Includes React, React DOM, Scheduler, React Three Fiber and three.js, all
// under the MIT license.`;

const options = {
  entryPoints: [path.join(here, "src/main.jsx")],
  outfile,
  bundle: true,
  format: "esm",
  target: "firefox140",
  minify: true,
  legalComments: "none",
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  banner: { js: banner },
  logLevel: "info",
};

if (!serve) {
  await esbuild.build(options);
} else {
  const context = await esbuild.context(options);
  await context.watch();
  // The dev page asks for the files by the paths below; the browser gets
  // them from chrome:// URLs instead.
  const routes = [
    ["/app.mjs", outfile],
    ["/zendia-welcome.css", "src/zen/welcome/zendia-welcome.css"],
    ["/welcome-background.mp4", "src/zen/welcome/welcome-background.mp4"],
    ["/zen-welcome.ftl", "locales/en-US/browser/browser/zen-welcome.ftl"],
    ["/favicons/", "src/zen/images/favicons/"],
    ["/", path.join(here, "dev/")],
  ];
  const types = {
    ".html": "text/html",
    ".mjs": "text/javascript",
    ".js": "text/javascript",
    ".css": "text/css",
    ".svg": "image/svg+xml",
    ".mp4": "video/mp4",
    ".ftl": "text/plain",
  };
  createServer((request, response) => {
    const url = new URL(request.url, "http://localhost");
    let pathname = url.pathname == "/" ? "/index.html" : url.pathname;
    if (pathname == "/wait") {
      // Holds the page's load event back, so `firefox --screenshot` takes
      // its picture after the preview has drawn.
      setTimeout(() => response.writeHead(204).end(), Number(url.searchParams.get("ms")) || 0);
      return;
    }
    for (const [prefix, target] of routes) {
      if (!pathname.startsWith(prefix)) {
        continue;
      }
      const base = path.resolve(repo, target);
      const file = prefix.endsWith("/")
        ? path.join(base, pathname.slice(prefix.length))
        : base;
      if (!file.startsWith(base) || !existsSync(file) || !statSync(file).isFile()) {
        continue;
      }
      response.writeHead(200, {
        "Content-Type": types[path.extname(file)] ?? "application/octet-stream",
        "Cache-Control": "no-store",
      });
      createReadStream(file).pipe(response);
      return;
    }
    response.writeHead(404).end("Not found");
  }).listen(4173, "127.0.0.1", () => {
    console.log("Onboarding dev page: http://127.0.0.1:4173/");
  });
}
